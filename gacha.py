"""単語ガチャ(Googleスプレッドシート版)

シートのA列に単語を1行ずつ書くだけ。1行目は見出し。
シートの共有設定は「リンクを知っている全員が閲覧可」にしてください。

使い方:
    python word_gacha_sheet.py        # 3語引く
    python word_gacha_sheet.py 10     # 10語引く
1回の抽選では同じ単語は出ません。
"""
import csv
import io
import random
import sys
import urllib.request

SHEET_ID = "1-VlnFIsUMX9O8c7UoKPwNiLqY-XpwTdeH8XgbJLm0e4"
GID = 0
URL = f"https://docs.google.com/spreadsheets/d/{SHEET_ID}/export?format=csv&gid={GID}"


def load_words():
    """A列の単語を読む。空行・重複登録は除く。"""
    text = urllib.request.urlopen(URL, timeout=15).read().decode("utf-8")
    rows = list(csv.reader(io.StringIO(text)))[1:]  # 1行目は見出し
    words = [r[0].strip() for r in rows if r and r[0].strip()]
    return list(dict.fromkeys(words))  # 重複登録を除く(順序は保つ)


def main():
    n = int(sys.argv[1]) if len(sys.argv) > 1 and sys.argv[1].isdigit() else 3
    try:
        words = load_words()
    except Exception as e:
        print("シートを読み込めませんでした。共有設定が「リンクを知っている全員が閲覧可」か確認してください。")
        print(f"({e})")
        return
    if not words:
        print("単語がありません。シートのA列(2行目以降)に単語を入力してください。")
        return
    if n > len(words):
        print(f"※ 登録は {len(words)} 語のため、{len(words)} 語を引きます。")

    for i, word in enumerate(random.sample(words, k=min(n, len(words))), 1):
        print(f"{i}. {word}")


if __name__ == "__main__":
    main()
